//! The Issue #50 frozen workload cells (Issue #50 §2).
//!
//! One local-text regime, eight document sizes:
//!
//! ```text
//! N = 128 KiB, 256 KiB, 512 KiB, 1 MiB, 2 MiB, 4 MiB, 8 MiB, 16 MiB
//! block unit = 128 bytes = 126 content bytes + LF + LF
//! M = N / 128 ; target block = floor(M / 2)
//! edit = zero-length insertion of "zzzzzzzz" at target * 128 + 63
//! container depth 0, no references, no definitions, no fences
//! ```
//!
//! The byte construction is the Campaign-2 controlled-N construction
//! (`campaign2::generators::case_n`) re-expressed over the *same public
//! helpers* (`para_block`, `PAD128_TEXT`, `LOCAL_TEXT_INSERT`). For every
//! point that Campaign-2 also has (`128KiB`, `1MiB`, `16MiB`) the
//! generated `pre_source`, `post_source` and `CanonicalEdit` are compared
//! **byte for byte** against `campaign2::generators::generate_cell` and
//! the run refuses to proceed on any difference. The five new points are
//! new diagnostic cells only: the Campaign-2 cell table and its identities
//! are not modified.

use markit_mdbench_campaign2::generators::{self, Axis};
use markit_mdbench_common::{
    CanonicalEdit, CaseId, CaseKeyV1, OperationKind, PayloadShape,
};

/// Cell labels in frozen ascending order.
pub const CELL_LABELS: [&str; 8] = [
    "128KiB", "256KiB", "512KiB", "1MiB", "2MiB", "4MiB", "8MiB", "16MiB",
];

/// Cell labels that Campaign-2's controlled-N axis also contains, and
/// whose generated bytes must therefore match it exactly.
pub const CAMPAIGN2_OVERLAP_LABELS: [&str; 3] = ["128KiB", "1MiB", "16MiB"];

/// The 128-byte block unit (126 content bytes + LF + LF).
pub const BLOCK_UNIT_BYTES: u64 = 128;
/// Content bytes per block.
pub const BLOCK_CONTENT_BYTES: usize = 126;
/// The frozen 8-byte insertion payload.
pub const INSERT_TEXT: &str = "zzzzzzzz";

/// One frozen #50 cell.
#[derive(Debug, Clone)]
pub struct Cell {
    pub label: String,
    pub n_bytes: u64,
    pub m_blocks: u64,
    pub target_block_index: u64,
    pub target_block_offset: u64,
    pub edit_start: u64,
    pub edit_end: u64,
    pub inserted_text: String,
    pub pre_sha256: String,
    pub post_sha256: String,
    pub edit_sha256: String,
    pub case_id_hex: String,
    /// Whether this cell is one of Campaign-2's controlled-N points and
    /// was byte-verified against the frozen generator.
    pub campaign2_overlap: bool,
    pub pre_source: String,
    pub post_source: String,
    pub edit: CanonicalEdit,
}

impl Cell {
    /// Expected restart distance in bytes (Issue #50 §2): the edit sits 63
    /// bytes into the target block, so the restart checkpoint at the
    /// target block start is 63 bytes before the edit.
    pub const EXPECTED_RESTART_DISTANCE: u64 = 63;
    /// Expected forward/convergence distance: the forward parse consumes
    /// the target block (128 B) plus the 8 inserted bytes.
    pub const EXPECTED_CONVERGENCE_DISTANCE: u64 = 136;
    /// Expected fresh blocks.
    pub const EXPECTED_FRESH_BLOCKS: u64 = 1;
    /// Expected fresh nodes.
    pub const EXPECTED_FRESH_NODES: u64 = 2;
    /// Expected unique post-source bytes inspected (the 128 B target block
    /// in post coordinates + the 8 inserted bytes + the 2-byte blank-line
    /// margin read).
    pub const EXPECTED_UNIQUE_POST_BYTES: u64 = 138;

    /// The edit's byte range in pre coordinates.
    pub fn edit_range(&self) -> (u64, u64) {
        (self.edit_start, self.edit_end)
    }

    /// Construction facts recorded with the cell (mirrors the Campaign-2
    /// construction record).
    pub fn construction(&self) -> Vec<(String, String)> {
        vec![
            ("n_bytes".to_string(), self.n_bytes.to_string()),
            ("block_unit_bytes".to_string(), BLOCK_UNIT_BYTES.to_string()),
            ("block_count".to_string(), self.m_blocks.to_string()),
            (
                "target_block_index".to_string(),
                self.target_block_index.to_string(),
            ),
            (
                "target_block_offset".to_string(),
                self.target_block_offset.to_string(),
            ),
            ("container_depth".to_string(), "0".to_string()),
            ("references".to_string(), "none".to_string()),
            ("definitions".to_string(), "none".to_string()),
            ("fences".to_string(), "none".to_string()),
        ]
    }

    pub fn to_json(&self) -> serde_json::Value {
        let mut facts = serde_json::Map::new();
        for (k, v) in self.construction() {
            facts.insert(k, serde_json::Value::String(v));
        }
        serde_json::json!({
            "label": self.label,
            "cell_id": format!("H4N-{}", self.label),
            "n_bytes": self.n_bytes,
            "m_blocks": self.m_blocks,
            "block_unit_bytes": BLOCK_UNIT_BYTES,
            "target_block_index": self.target_block_index,
            "target_block_offset": self.target_block_offset,
            "edit_start": self.edit_start,
            "edit_end": self.edit_end,
            "inserted_text": self.inserted_text,
            "pre_sha256": self.pre_sha256,
            "post_sha256": self.post_sha256,
            "edit_sha256": self.edit_sha256,
            "case_id_hex": self.case_id_hex,
            "campaign2_overlap": self.campaign2_overlap,
            "generator_id": generators::GENERATOR_ID,
            "generator_version": generators::GENERATOR_VERSION,
            "construction": serde_json::Value::Object(facts),
            "expected": {
                "restart_distance": Self::EXPECTED_RESTART_DISTANCE,
                "convergence_distance": Self::EXPECTED_CONVERGENCE_DISTANCE,
                "fresh_blocks": Self::EXPECTED_FRESH_BLOCKS,
                "fresh_nodes": Self::EXPECTED_FRESH_NODES,
                "unique_post_bytes": Self::EXPECTED_UNIQUE_POST_BYTES,
            },
        })
    }
}

/// Parse a label such as `128KiB` / `1MiB` into bytes.
fn label_to_bytes(label: &str) -> Result<u64, String> {
    let (number, unit) = if let Some(rest) = label.strip_suffix("KiB") {
        (rest, 1024u64)
    } else if let Some(rest) = label.strip_suffix("MiB") {
        (rest, 1024u64 * 1024)
    } else {
        return Err(format!("unknown size unit in cell label {label:?}"));
    };
    let value: u64 = number
        .parse()
        .map_err(|e| format!("cell label {label:?}: {e}"))?;
    Ok(value * unit)
}

/// Build the Campaign-2 controlled-N bytes for an arbitrary size, using
/// the frozen public helpers.
fn build_pre(n_bytes: u64) -> Result<(String, u64, u64), String> {
    if n_bytes % BLOCK_UNIT_BYTES != 0 || n_bytes < 512 {
        return Err(format!(
            "N = {n_bytes} is not a positive multiple of {BLOCK_UNIT_BYTES} (>= 512)"
        ));
    }
    let blocks = n_bytes / BLOCK_UNIT_BYTES;
    let target = blocks / 2;
    let mut pre = String::with_capacity(n_bytes as usize);
    for b in 0..blocks {
        pre.push_str(&generators::para_block(
            BLOCK_CONTENT_BYTES,
            b as usize,
        ));
    }
    if pre.len() as u64 != n_bytes {
        return Err(format!(
            "constructed source length {} != N {}",
            pre.len(),
            n_bytes
        ));
    }
    Ok((pre, blocks, target))
}

/// Build one cell by label.
pub fn cell_by_label(label: &str) -> Result<Cell, String> {
    let n_bytes = label_to_bytes(label)?;
    let (pre, blocks, target) = build_pre(n_bytes)?;
    let target_offset = target * BLOCK_UNIT_BYTES;
    let edit_start = target_offset + 63;
    let edit = CanonicalEdit::new(edit_start as usize, edit_start as usize, INSERT_TEXT)
        .map_err(|e| format!("cell {label}: constructing the canonical edit: {e:?}"))?;

    let pre_source =
        markit_mdbench_common::Source::new(markit_mdbench_common::SourceId(0), pre.clone());
    let post = edit
        .apply(&pre_source, markit_mdbench_common::SourceId(1))
        .map_err(|e| format!("cell {label}: applying the edit: {e:?}"))?
        .as_str()
        .to_string();

    let overlap = CAMPAIGN2_OVERLAP_LABELS.contains(&label);
    let case_id_hex = if overlap {
        // Authority: the frozen Campaign-2 cell identity.
        let frozen = generators::generate_cell(Axis::N, label)?;
        verify_against_campaign2(&frozen, &pre, &post, &edit, edit_start)?;
        frozen.case_id_hex.clone()
    } else {
        // A NEW diagnostic cell identity; Campaign-2's table is untouched.
        let key = CaseKeyV1 {
            payload_id: format!("h4n:{}", label.to_lowercase()),
            payload_shape: PayloadShape::Mixed,
            payload_size_bytes: pre.len() as u64,
            old_source_sha256: digest32(&pre),
            operation: OperationKind::classify(&edit),
            edit_start_byte: Some(edit.start_byte()),
            edit_end_byte: Some(edit.end_byte()),
            inserted_text_sha256: Some(digest32(INSERT_TEXT)),
            generator_id: Some(generators::GENERATOR_ID.to_string()),
            generator_seed: Some(n_bytes),
        }
        .validated()
        .map_err(|e| format!("cell {label}: case key: {e:?}"))?;
        CaseId::from_key(&key).hex()
    };

    Ok(Cell {
        label: label.to_string(),
        n_bytes,
        m_blocks: blocks,
        target_block_index: target,
        target_block_offset: target_offset,
        edit_start,
        edit_end: edit_start,
        inserted_text: INSERT_TEXT.to_string(),
        pre_sha256: markit_mdbench_campaign2::sha256_hex(pre.as_bytes()),
        post_sha256: markit_mdbench_campaign2::sha256_hex(post.as_bytes()),
        edit_sha256: markit_mdbench_campaign2::sha256_hex(INSERT_TEXT.as_bytes()),
        case_id_hex,
        campaign2_overlap: overlap,
        pre_source: pre,
        post_source: post,
        edit,
    })
}

/// Every cell, in frozen ascending order.
pub fn all_cells() -> Result<Vec<Cell>, String> {
    CELL_LABELS.iter().map(|l| cell_by_label(l)).collect()
}

/// Byte-for-byte comparison against the frozen Campaign-2 generator.
fn verify_against_campaign2(
    frozen: &generators::ControlledCase,
    pre: &str,
    post: &str,
    edit: &CanonicalEdit,
    edit_start: u64,
) -> Result<(), String> {
    if frozen.pre_source != pre {
        return Err(format!(
            "C-N byte mismatch for {}: pre_source differs from the frozen generator \
             (frozen {} bytes, ours {} bytes)",
            frozen.axis_label,
            frozen.pre_source.len(),
            pre.len()
        ));
    }
    if frozen.post_source != post {
        return Err(format!(
            "C-N byte mismatch for {}: post_source differs from the frozen generator",
            frozen.axis_label
        ));
    }
    if frozen.edit.start_byte() != edit.start_byte()
        || frozen.edit.end_byte() != edit.end_byte()
        || frozen.edit.inserted_text() != edit.inserted_text()
    {
        return Err(format!(
            "C-N edit mismatch for {}: frozen {:?}..{:?} {:?}, ours {:?}..{:?} {:?}",
            frozen.axis_label,
            frozen.edit.start_byte(),
            frozen.edit.end_byte(),
            frozen.edit.inserted_text(),
            edit.start_byte(),
            edit.end_byte(),
            edit.inserted_text()
        ));
    }
    if frozen.edit_start != edit_start {
        return Err(format!(
            "C-N edit offset mismatch for {}: frozen {}, ours {}",
            frozen.axis_label, frozen.edit_start, edit_start
        ));
    }
    Ok(())
}

fn digest32(bytes: &str) -> [u8; 32] {
    let hex = markit_mdbench_campaign2::sha256_hex(bytes.as_bytes());
    let mut out = [0u8; 32];
    for i in 0..32 {
        out[i] = u8::from_str_radix(&hex[i * 2..i * 2 + 2], 16).expect("hex digit");
    }
    out
}

/// SHA256 (lowercase hex) of a byte slice.
pub fn sha256_hex(bytes: &[u8]) -> String {
    markit_mdbench_campaign2::sha256_hex(bytes)
}
