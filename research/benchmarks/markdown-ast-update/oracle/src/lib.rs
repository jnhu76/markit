//! markit-mdbench-oracle — normalization + correctness authority.
//!
//! R1 shipped only the scalar checksum hook. R4 adds the real
//! NORMALIZED-RESULT-v1 semantic authority:
//!
//! - [`normalized`] — the frozen vocabulary (13 node kinds, UTF-8 byte
//!   half-open spans, frozen value fields, structural equality);
//! - [`normalized_checksum`] — the deterministic checksum derived from
//!   the fully materialized normalized result (fills
//!   `Completed::result_checksum`; never a correctness proof);
//! - [`node_path_at`] — the frozen NODE_PATH_AT query over the
//!   normalized tree;
//! - [`NormalizeV1`] + [`ReferenceOracle`] — later horses expose their
//!   state as a [`NormalizedDocument`] and are checked structurally
//!   against an expected H0 normalized result;
//! - [`fixture`] — loader for the 43 hand-authored golden grammar
//!   fixtures (independent semantic authority, never generated by a
//!   parser);
//! - [`validate`] — the shared NORMALIZED-RESULT-v1 conformance gate
//!   (exact field-kind legality, zero-length rule, `FencedCode.content`
//!   interval rule) applied to fixture expected trees at load time, to
//!   every H0 result, and reusable by later horses.
//!
//! Oracle execution is strictly OUTSIDE `T_native` — the runner invokes
//! hooks only after all timing has stopped, and the oracle never touches
//! a clock.

pub mod fixture;
pub mod normalized;
pub mod validate;

use markit_mdbench_common::Completed;
use markit_mdbench_common::CorrectnessStatus;

pub use normalized::{
    node_path_at, normalized_checksum, Node, NodeKind, NormalizedDocument, PathNode,
};
pub use validate::{validate_normalized, validate_root};

/// Generic correctness hook over a mechanism's completed result.
pub trait CorrectnessHook<S> {
    fn verify(&self, completed: &Completed<S>) -> CorrectnessStatus;
}

/// A mechanism state that can be projected onto the frozen
/// NORMALIZED-RESULT-v1 vocabulary. Horses implement this on their own
/// native state; they never have to expose parser-internal structures.
pub trait NormalizeV1 {
    fn normalize_v1(&self) -> NormalizedDocument;
}

/// The structural reference oracle: compares the state's normalized
/// result against an expected normalized document (by construction the
/// H0 clean-parse result). WRONG structure is `WrongResult` — never a
/// checksum verdict.
///
/// The expected document is plain data; holding it does not give the
/// oracle access to any parser, and the comparison is `PartialEq` over
/// the vocabulary types, so correctness is never tautological.
#[derive(Debug, Clone)]
pub struct ReferenceOracle {
    expected: NormalizedDocument,
}

impl ReferenceOracle {
    pub fn new(expected: NormalizedDocument) -> Self {
        Self { expected }
    }

    /// Structural comparison without the hook plumbing (used by
    /// differential tests that compare two normalized results directly).
    pub fn matches(&self, actual: &NormalizedDocument) -> bool {
        actual == &self.expected
    }
}

impl<S: NormalizeV1> CorrectnessHook<S> for ReferenceOracle {
    fn verify(&self, completed: &Completed<S>) -> CorrectnessStatus {
        if completed.state.normalize_v1() == self.expected {
            CorrectnessStatus::Pass
        } else {
            CorrectnessStatus::WrongResult
        }
    }
}

/// R1 hook: compare the deterministic scalar checksum recorded in
/// [`Completed::result_checksum`] against the expected value derived by
/// the same documented formula.
pub struct ScalarChecksumHook {
    expected: u64,
}

impl ScalarChecksumHook {
    pub fn new(expected: u64) -> Self {
        Self { expected }
    }
}

impl<S> CorrectnessHook<S> for ScalarChecksumHook {
    fn verify(&self, completed: &Completed<S>) -> CorrectnessStatus {
        if completed.result_checksum == self.expected {
            CorrectnessStatus::Pass
        } else {
            CorrectnessStatus::WrongResult
        }
    }
}

/// Hook that records `NOT_CHECKED`: used when a lane intentionally skips
/// correctness (never silently passes).
pub struct NotCheckedHook;

impl<S> CorrectnessHook<S> for NotCheckedHook {
    fn verify(&self, _completed: &Completed<S>) -> CorrectnessStatus {
        CorrectnessStatus::NotChecked
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use markit_mdbench_common::Completed;

    #[derive(Debug, Clone, PartialEq, Eq)]
    struct FakeState(NormalizedDocument);

    impl NormalizeV1 for FakeState {
        fn normalize_v1(&self) -> NormalizedDocument {
            self.0.clone()
        }
    }

    fn para_doc(text_end: usize) -> NormalizedDocument {
        let mut root = Node::new(NodeKind::Document, 0, text_end + 1);
        root.children
            .push(Node::new(NodeKind::Paragraph, 0, text_end));
        NormalizedDocument::new(root)
    }

    #[test]
    fn scalar_hook_reports_pass_and_wrong_result() {
        let done = Completed {
            state: (),
            result_checksum: 42,
        };
        assert_eq!(
            ScalarChecksumHook::new(42).verify(&done),
            CorrectnessStatus::Pass
        );
        assert_eq!(
            ScalarChecksumHook::new(43).verify(&done),
            CorrectnessStatus::WrongResult
        );
        assert_eq!(NotCheckedHook.verify(&done), CorrectnessStatus::NotChecked);
    }

    #[test]
    fn reference_oracle_compares_structure_not_checksum() {
        let expected = para_doc(11);
        let oracle = ReferenceOracle::new(expected.clone());
        let done = Completed {
            state: FakeState(para_doc(11)),
            result_checksum: 12345, // deliberately not the normalized checksum
        };
        assert_eq!(oracle.verify(&done), CorrectnessStatus::Pass);
        let wrong = Completed {
            state: FakeState(para_doc(12)),
            result_checksum: normalized_checksum(&expected),
        };
        // even a "matching" checksum cannot smuggle a wrong structure through
        assert_eq!(oracle.verify(&wrong), CorrectnessStatus::WrongResult);
    }
}
